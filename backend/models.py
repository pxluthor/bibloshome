
from typing import Optional, Dict, Any, List
from sqlmodel import Field, SQLModel
from datetime import datetime, timezone
from sqlalchemy import Column, JSON, UniqueConstraint, LargeBinary, Text


def utcnow() -> datetime:
    # sqlmodel >= 0.0.47 rejects naive datetimes on insert/update
    return datetime.now(timezone.utc)


class Livro(SQLModel, table=True):
    __tablename__ = "livros"

    id: Optional[int] = Field(default=None, primary_key=True)
    titulo: Optional[str]  = Field(default=None, max_length=500)
    autor: Optional[str]
    ano: Optional[int]
    editora: Optional[str]
    genero: Optional[str]
    area: Optional[str]    = Field(default=None, max_length=500)
    idioma: Optional[str]
    paginas: Optional[int]
    sinopse: Optional[str]
    caminho: Optional[str] = Field(default=None, max_length=1000)
    capa: Optional[bytes]  = Field(default=None, sa_column=Column(LargeBinary(length=16777215)))  # MEDIUMBLOB
    data_adicao: Optional[datetime] = Field(default_factory=utcnow)
    tags: Optional[List] = Field(default=None, sa_column=Column(JSON))
    is_duplicate: bool = Field(default=False)

class LivroRead(SQLModel):
    id: int
    titulo: Optional[str]
    autor: Optional[str]
    ano: Optional[int]
    genero: Optional[str]
    idioma: Optional[str]
    paginas: Optional[int]
    area: Optional[str]
    editora: Optional[str]
    sinopse: Optional[str]
    caminho: Optional[str]
    tags: Optional[List] = None
    is_duplicate: bool = False

class LivroUpdate(SQLModel):
    titulo: Optional[str] = None
    autor: Optional[str] = None
    area: Optional[str] = None
